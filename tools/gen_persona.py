#!/usr/bin/env python3
"""Writes js/persona.js: a copy of Quark's personality and reply format for the "your own Gemini key" mode, where the browser
talks to Gemini directly. The text comes from backend/server.py (the single source of truth) so the two can never drift.

    python3 tools/gen_persona.py            # rewrite js/persona.js
    python3 tools/gen_persona.py --check    # exit 1 if js/persona.js is out of date (tests/test_persona_sync.py runs this)
"""
import importlib.util
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "js", "persona.js")


def render():
    os.environ.setdefault("MOCK", "1")                      # loading the backend must not need a key
    spec = importlib.util.spec_from_file_location("quark_brain", os.path.join(ROOT, "backend", "server.py"))
    b = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(b)
    j = lambda v: json.dumps(v, indent=2, ensure_ascii=False)
    return f"""// GENERATED by tools/gen_persona.py from backend/server.py: do not edit by hand (run the script again instead).
// Quark's personality, the reply format and the Gemini response schema, for the mode where the browser calls Gemini directly
// with the user's own key (js/geminikey.js). The server keeps its own copy of the same text.

export const CORE = {json.dumps(b.CORE, ensure_ascii=False)};
export const MODE_ADULT = {json.dumps(b.MODE_ADULT, ensure_ascii=False)};
export const MODE_FOCUS = {json.dumps(b.MODE_FOCUS, ensure_ascii=False)};
export const MODE_KID = {json.dumps(b.MODE_KID, ensure_ascii=False)};
export const OUTPUT_FORMAT = {json.dumps(b.OUTPUT_FORMAT, ensure_ascii=False)};

/** The system prompt for a mode: 'kid', or adult (optionally the quiet focus buddy). */
export function buildSystem(mode, focus) {{
  const extra = mode === 'kid' ? MODE_KID : focus ? MODE_ADULT + MODE_FOCUS : MODE_ADULT;
  return CORE + '\\n' + extra + '\\n' + OUTPUT_FORMAT;
}}

/** What Gemini must answer with (its schema dialect: upper-case type names). */
export const RESPONSE_SCHEMA = {j(b.RESPONSE_SCHEMA)};

/** Kid mode asks Gemini for stricter content filtering. */
export const KID_SAFETY = {j(b.KID_SAFETY)};
"""


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("js/persona.js is out of date: run python3 tools/gen_persona.py")
            sys.exit(1)
        print("js/persona.js is up to date")
    else:
        open(OUT, "w", encoding="utf-8").write(text)
        print("wrote", OUT, len(text), "bytes")
